SELECT
    INITCAP(TRIM(COMMODITY)) AS COMMODITY,
    INITCAP(TRIM(MARKET)) AS MARKET,
    PRICE_PER_KG,
    UPPER(TRIM(CURRENCY)) AS CURRENCY,
    UPPER(TRIM(UNIT)) AS UNIT,
    PRICE_DATE,
    UPPER(TRIM(DATA_SOURCE)) AS DATA_SOURCE
FROM {{ source('atmosync_commodity_raw', 'commodity_prices') }}
WHERE
    COMMODITY IS NOT NULL
    AND MARKET IS NOT NULL
    AND PRICE_PER_KG > 0
    AND PRICE_DATE IS NOT NULL
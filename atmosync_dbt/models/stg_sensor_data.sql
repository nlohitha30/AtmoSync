
SELECT
    UPPER(TRIM(CONTAINER_ID)) AS CONTAINER_ID,
    INITCAP(TRIM(COMMODITY)) AS COMMODITY,
    TEMPERATURE_C,
    HUMIDITY_PCT,
    VIBRATION,
    TIMESTAMP
FROM {{ source('atmosync_raw', 'sensor_data') }}
WHERE
    CONTAINER_ID IS NOT NULL
    AND COMMODITY IS NOT NULL
    AND TEMPERATURE_C IS NOT NULL
    AND HUMIDITY_PCT BETWEEN 0 AND 100
    AND VIBRATION >= 0
